// The bounds the request bodies in openapi.json set, written for the
// clients' forms, so a length lives once: in the Zod schema it comes from.

type JsonSchema = {
  type?: string;
  properties?: Record<string, JsonSchema>;
  items?: JsonSchema;
  enum?: string[];
  minLength?: number;
  maxLength?: number;
  minimum?: number;
  maximum?: number;
  minItems?: number;
  maxItems?: number;
};

type Limit = {[key: string]: number | Limit};

const BOUNDS = [
  'minLength',
  'maxLength',
  'minimum',
  'maximum',
  'minItems',
  'maxItems',
] as const;

function isEmpty(limit: Limit): boolean {
  return Object.keys(limit).length === 0;
}

// The fields of an object, each with what bounds it. A field without any
// is left out.
function fieldsOf(schema: JsonSchema, locales: readonly string[]): Limit {
  const fields: Limit = {};

  for (const [name, field] of Object.entries(schema.properties ?? {})) {
    const limit = limitOf(field, locales);

    if (!isEmpty(limit)) {
      fields[name] = limit;
    }
  }

  return fields;
}

// A value written once per language has the same bounds in each, so it is
// given once, as the forms check every language alike.
function perLocale(fields: Limit, locales: readonly string[]): Limit | null {
  const names = Object.keys(fields);
  const [first] = Object.values(fields);
  const same = Object.values(fields).every(
    (limit) => JSON.stringify(limit) === JSON.stringify(first),
  );

  return names.length === locales.length &&
    names.every((name) => locales.includes(name)) &&
    same &&
    typeof first === 'object'
    ? first
    : null;
}

function limitOf(schema: JsonSchema, locales: readonly string[]): Limit {
  const limit: Limit = {};

  for (const bound of BOUNDS) {
    const value = schema[bound];

    if (value !== undefined) {
      limit[bound] = value;
    }
  }

  if (schema.items) {
    const items = limitOf(schema.items, locales);

    if (!isEmpty(items)) {
      limit.items = items;
    }
  }

  if (schema.properties) {
    const fields = fieldsOf(schema, locales);

    return perLocale(fields, locales) ?? {...limit, ...fields};
  }

  return limit;
}

// Every request body with a bounded field, by its name in openapi.json.
// The schemas the document also lists as input are the same bodies again.
export function limitsOf(document: object): Limit {
  // Fastify's swagger types the document loosely; ours is OpenAPI 3.
  const {components} = document as {
    components?: {schemas?: Record<string, JsonSchema>};
  };
  const schemas = components?.schemas ?? {};
  const locales = schemas.Locale?.enum ?? [];
  const limits: Limit = {};

  const names = Object.keys(schemas).sort();

  for (const name of names) {
    const schema = schemas[name];

    if (!schema || !name.endsWith('Body')) {
      continue;
    }

    const fields = fieldsOf(schema, locales);

    if (!isEmpty(fields)) {
      limits[name] = fields;
    }
  }

  return limits;
}

export function limitsModule(limits: Limit): string {
  return [
    '// Generated by server/scripts/generate-types.ts from the bounds in',
    "// server/openapi.json and the server's password rule. Do not edit.",
    '',
    `export const limits = ${JSON.stringify(limits, null, 2)} as const;`,
    '',
  ].join('\n');
}
