import {readFileSync, writeFileSync} from 'node:fs';
import {createRequire} from 'node:module';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

// Same Ionicons glyphs as @expo/vector-icons. The web build uses the
// package SVG, not the icon font.
const ICONS = {
  'calendar-outline': 'CalendarOutlineIcon',
  'time-outline': 'TimeOutlineIcon',
  'home-outline': 'HomeOutlineIcon',
  'lock-closed': 'LockClosedIcon',
  'chevron-forward': 'ChevronForwardIcon',
  'chevron-back': 'ChevronBackIcon',
  'alert-circle': 'AlertCircleIcon',
  'people-outline': 'PeopleOutlineIcon',
  'grid-outline': 'GridOutlineIcon',
  'megaphone-outline': 'MegaphoneOutlineIcon',
  'settings-outline': 'SettingsOutlineIcon',
  'eye-outline': 'EyeOutlineIcon',
  'eye-off-outline': 'EyeOffOutlineIcon',
  add: 'AddIcon',
};

const ATTRIBUTES = {
  'stroke-width': 'strokeWidth',
  'stroke-linecap': 'strokeLinecap',
  'stroke-linejoin': 'strokeLinejoin',
  'stroke-miterlimit': 'strokeMiterlimit',
  'stroke-dasharray': 'strokeDasharray',
  'fill-rule': 'fillRule',
  'clip-rule': 'clipRule',
  'stop-color': 'stopColor',
};

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Found the way Node resolves the package, since the workspace may hoist it
// out of web/node_modules.
const svgs = resolve(
  dirname(
    createRequire(import.meta.url).resolve('ionicons/dist/ionicons.json'),
  ),
  'svg',
);

function bodyOf(name) {
  const file = resolve(svgs, `${name}.svg`);
  const source = readFileSync(file, 'utf8');
  const inner = source.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');

  return inner
    .replace(/<title>.*?<\/title>/g, '')
    .replace(/([a-z]+(?:-[a-z]+)+)=/g, (_match, attribute) => {
      const mapped = ATTRIBUTES[attribute];
      if (!mapped) {
        throw new Error(`unmapped SVG attribute: ${attribute}`);
      }
      return `${mapped}=`;
    })
    .replace(/\s*\/>/g, ' />')
    .trim();
}

writeFileSync(
  resolve(root, 'src/components/icons/types.ts'),
  `// Generated by npm run generate. Do not edit by hand.
export type IconProps = {
  size: number;
  className?: string;
};
`,
);

const names = [];

for (const [icon, component] of Object.entries(ICONS)) {
  names.push(component);
  writeFileSync(
    resolve(root, `src/components/icons/${component}.tsx`),
    `// Generated from ionicons/${icon}.svg by npm run generate. Do not edit by hand.
import type {IconProps} from '@/components/icons/types';

export function ${component}({size, className}: IconProps) {
  return (
    <svg
      width={size}
      height={size}
      viewBox='0 0 512 512'
      fill='currentColor'
      className={\`shrink-0 \${className ?? ''}\`}
      aria-hidden='true'
    >
      ${bodyOf(icon)}
    </svg>
  );
}
`,
  );
}

writeFileSync(
  resolve(root, 'src/components/icons/index.ts'),
  `// Generated by npm run generate. Do not edit by hand.\n${names
    .map((name) => `export {${name}} from '@/components/icons/${name}';`)
    .join('\n')}\nexport type {IconProps} from '@/components/icons/types';\n`,
);

console.log(`icons: ${names.length} components from ionicons`);
